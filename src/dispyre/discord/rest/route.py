"""The types the generated REST layer is built on: `Route`, `Requester` and `compact`.

`routes.py` holds one `Route` per endpoint and `client.py` one `RestApi` method per
route. Both are generated by `scripts/generate_rest.py`. This module is written by hand.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, Literal
from urllib.parse import quote

if TYPE_CHECKING:
    from collections.abc import Mapping

BASE_URL = "https://discord.com/api/v10"


@dataclass(frozen=True, slots=True)
class Route:
    """One REST endpoint: where it lives, what it takes and what it returns."""

    operation_id: str
    method: Literal["GET", "POST", "PUT", "PATCH", "DELETE"]
    path: str
    """Path template with `{name}` placeholders, such as `/channels/{channel_id}/messages`."""
    path_params: tuple[str, ...] = ()
    query: tuple[str, ...] = ()
    required_query: tuple[str, ...] = ()
    body: Any = None
    """Type of the request body, or `None` when the endpoint takes none."""
    body_required: bool = False
    multipart: bool = False
    """The endpoint also accepts `multipart/form-data`, so files can ride along."""
    form: bool = False
    """The endpoint takes `application/x-www-form-urlencoded` instead of JSON."""
    response: Any = None
    """Type the response decodes into, or `None` for an empty response."""
    summary: str = ""
    docs: str = ""
    bot: bool = False
    """A bot token may call the endpoint."""
    oauth2_scopes: tuple[str, ...] = ()
    """OAuth2 scopes that let a bearer token call the endpoint, empty if none does."""
    oauth2: bool = False
    """A bearer token may call the endpoint (with any of `oauth2_scopes`, if listed)."""
    anonymous: bool = False
    """The endpoint can be called without credentials."""
    audit_log_reason: bool = False
    """The endpoint reads the `X-Audit-Log-Reason` header."""
    deprecated: bool = False
    source: Literal["openapi", "docs"] = "openapi"
    """Where the route came from: the OpenAPI spec, or only the docs' markdown."""

    def url(self, *, base: str = BASE_URL, **params: object) -> str:
        """Fill the path template. Raises `KeyError` naming a missing path parameter."""
        missing = [name for name in self.path_params if name not in params]
        if missing:
            msg = f"{self.operation_id} needs path parameters {missing}"
            raise KeyError(msg)
        values = {name: quote(str(params[name]), safe="@") for name in self.path_params}
        return base + self.path.format(**values)


def compact(values: Mapping[str, Any]) -> dict[str, Any]:
    """Drop the `None` entries, so unset optional query parameters aren't sent."""
    return {key: value for key, value in values.items() if value is not None}


class Requester(ABC):
    """Anything that can send a `Route`; subclass it with your HTTP client of choice."""

    @abstractmethod
    async def request(  # noqa: PLR0913
        self,
        route: Route,
        *,
        path: Mapping[str, Any],
        query: Mapping[str, Any],
        body: Any = None,  # noqa: ANN401 - JSON-ready data from `dispyre.decode.encode`
        files: Mapping[str, bytes] | None = None,
        reason: str | None = None,
    ) -> Any:  # noqa: ANN401 - the decoded JSON body, `bytes` or `str`
        """Send the request and return the parsed response body.

        `path` fills `route.path`, `query` is already stripped of unset values and `body` is
        ready for `json.dumps`. With `files`, send `multipart/form-data` (the body goes in a
        `payload_json` part). Send `reason` as the `X-Audit-Log-Reason` header.
        """
