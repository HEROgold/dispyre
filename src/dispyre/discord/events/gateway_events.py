class GuildCreate(Guild):
    """Lazy-load for unavailable guild, guild became available, or user joined a new guild.

    This event can be sent in three different scenarios:

    1. When a user is initially connecting, to lazily load and backfill information for all
      unavailable guilds sent in the Ready event. Guilds that are unavailable due to an outage will
      send a Guild Delete event.
    2. When a Guild becomes available again to the client.
    3. When the current user joins a new Guild.

    The inner payload can be:

    - An available Guild: a guild object with extra fields, as noted below.
    - An unavailable Guild: an unavailable guild object.

    Note: During an outage, the guild object in scenarios 1 and 3 may be marked as unavailable.

    Warning: If your bot does not have the GUILD_PRESENCES Gateway Intent, or if the guild has over
    75k members, members and presences returned in this event will only contain your bot and users
    in voice channels.

    Receive event `GUILD_CREATE`.

    https://docs.discord.com/developers/events/gateway-events#guild-create
    """

    joined_at: ISO8601Timestamp
    """When this guild was joined at"""

    large: bool
    """true if this is considered a large guild"""

    unavailable: bool | None = None
    """true if this guild is unavailable due to an outage"""

    member_count: int
    """Total number of members in this guild"""

    voice_states: list[PartialVoiceState]
    """States of members currently in voice channels; lacks the guild_id key"""

    members: list[GuildMember]
    """Users in the guild"""

    channels: list[Channel]
    """Channels in the guild"""

    threads: list[Channel]
    """All active threads in the guild that current user has permission to view"""

    presences: list[PresenceUpdate]
    """
    Presences of the members in the guild, will only include non-offline members if the size is
    greater than large threshold
    """

    stage_instances: list[StageInstance]
    """Stage instances in the guild"""

    guild_scheduled_events: list[GuildScheduledEvent]
    """Scheduled events in the guild"""

    soundboard_sounds: list[SoundboardSound]
    """Soundboard sounds in the guild"""


