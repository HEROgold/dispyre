class RequestGuildMembers:
    """Requests members for a guild.

    Used to request all members for a guild or a list of guilds. When initially connecting, if you
    don't have the GUILD_PRESENCES Gateway Intent, or if the guild is over 75k members, it will only
    send members who are in voice, plus the member for you (the connecting user). Otherwise, if a
    guild has over large_threshold members (value in the Gateway Identify), it will only send
    members who are online, have a role, have a nickname, or are in a voice channel, and if it has
    under large_threshold members, it will send all members. If a client wishes to receive
    additional members, they need to explicitly request them via this operation. The server will
    send Guild Members Chunk events in response with up to 1000 members per chunk until all members
    that match the request have been sent.

    Due to our privacy and infrastructural concerns with this feature, there are some limitations
    that apply:

    - GUILD_PRESENCES intent is required to set presences = true. Otherwise, it will always be false
    - GUILD_MEMBERS intent is required to request the entire member list - (query='', limit=0<=n)
    - You will be limited to requesting 1 guild_id per request
    - Requesting a prefix (query parameter) will return a maximum of 100 members
    - Requesting user_ids will continue to be limited to returning 100 members

    Note: We are introducing a new rate limit to the Request Guild Members opcode. See Introducing
    Rate Limit When Requesting All Guild Members for more information and timeline on this new rate
    limit.

    Note: Nonce can only be up to 32 bytes. If you send an invalid nonce it will be ignored and the
    reply member_chunk(s) will not have a nonce set.

    Send event `REQUEST_GUILD_MEMBERS`, opcode 8.

    https://docs.discord.com/developers/events/gateway-events#request-guild-members
    """

    guild_id: Snowflake
    """
    ID of the guild to get members for

    Required: true.
    """

    query: str | None = None
    """
    string that username starts with, or an empty string to return all members

    Required: one of query or user_ids.
    """

    limit: int
    """
    maximum number of members to send matching the query; a limit of 0 can be used with an empty
    string query to return all members

    Required: true when specifying query.
    """

    presences: bool | None = None
    """
    used to specify if we want the presences of the matched members

    Required: false.
    """

    user_ids: Snowflake | list[Snowflake] | None = None
    """
    used to specify which users you wish to fetch

    Required: one of query or user_ids.
    """

    nonce: str | None = None
    """
    nonce to identify the Guild Members Chunk response

    Required: false.
    """


