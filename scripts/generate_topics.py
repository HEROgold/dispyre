def render_page(page: str, items: list[Item], owner: dict[str, str], tails: list[str]) -> str:
    local = {item.name for item in items}
    used: set[str] = set()
    bodies: list[str] = []
    for item in items:
        if isinstance(item, Enum):
            bodies.append(render_enum(item))
        elif isinstance(item, Computed):
            bodies.append(render_computed(item))
            used.add("Snowflake")
        else:
            bodies.append(render_model(item))
            for f in item.fields:
                used.update(re.findall(r"[A-Za-z_]\w*", f.annotation))
    tail_text = "\n".join(tails)
    used.update(re.findall(r"[A-Za-z_]\w*", re.sub(r"\"\"\"[\s\S]*?\"\"\"", "", tail_text)))
    heading = module_of(page).replace("_", " ")
    lines = [
        (
            f'"""Enums and models for Discord\'s {heading} docs page.\n\n'
            f'{GENERATED_MARKER} from\n{DOCS_ROOT}/developers/{page}. Do not edit by hand.\n"""\n\n'
            "from __future__ import annotations\n\n"
        )
    ]
    if bases := sorted({item.base for item in items if isinstance(item, Enum)}):
        lines.append(f"from enum import {', '.join(bases)}\n")
    if "Any" in used:
        lines.append("from typing import Any\n")
    if any(isinstance(item, Model) for item in items):
        lines.append("\nfrom dispyre.base import model\n")
    if aliases := sorted(used & {"ISO8601Timestamp", "Snowflake"}):
        lines.append(f"from {RESOURCES_PACKAGE}._types import {', '.join(aliases)}\n")
    imports: dict[str, list[str]] = {}
    for name in sorted(used - local):
        if name in owner and owner[name] != f"{PACKAGE}.{module_of(page)}":
            imports.setdefault(owner[name], []).append(name)
    lines.extend(
        f"from {mod} import {', '.join(names)}\n" for mod, names in sorted(imports.items())
    )
    exported = ", ".join(f'"{name}"' for name in sorted(local))
    tail_names = re.findall(r"^([A-Z][A-Z_]+)\b", tail_text, re.MULTILINE)
    exported = ", ".join([exported, *(f'"{n}"' for n in tail_names)]).strip(", ")
    return (
        "".join(lines)
        + f"\n__all__ = [{exported}]\n\n\n"
        + "\n\n\n".join(bodies)
        + ("\n\n\n" + "\n\n\n".join(tails) if tails else "")
        + "\n"
    )


def render_init(exports: dict[str, list[str]]) -> str:
    imports = "".join(
        f"from {PACKAGE}.{module} import {', '.join(sorted(names))}\n"
        for module, names in exports.items()
        if names
    )
    listing = "".join(
        f'    "{name}",\n' for name in sorted(n for ns in exports.values() for n in ns)
    )
    return (
        f'"""Enums, models and registries from Discord\'s topic pages.\n\n{GENERATED_MARKER}. Do not edit by hand.\n"""\n\n'
        f"{imports}\n__all__ = [\n{listing}]\n"
    )


