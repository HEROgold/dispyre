def render_unions(per_page: dict[str, list[Item]], owner: dict[str, str], plan: Plan) -> str:
    """`unions.py`: classes by component type and by interaction type."""
    enums = {i.name: i for items in per_page.values() for i in items if isinstance(i, Enum)}
    used: set[str] = set()
    blocks: list[str] = []

    def table(
        enum_name: str, label: str, lookup: dict[str, str] | None
    ) -> list[tuple[str, int, str]]:
        enum = enums.get(enum_name)
        if enum is None:
            plan.notes.append(f"{enum_name} not found; no {label} table")
            return []
        rows = []
        for member in enum.members:
            target = (
                lookup.get(member.name)
                if lookup is not None
                else pascal(member.name.replace("_", " ").title())
            )
            if target in owner and (lookup is not None or owner[target] != enum_name):
                rows.append((member.name, int(member.value), target))
            elif target:
                plan.notes.append(f"{label}: no class {target} for {enum_name}.{member.name}")
        return rows

    for enum_name, label, const, lookup, alias, doc in (
        (
            "ComponentTypes",
            "component",
            "COMPONENT_BY_TYPE",
            None,
            "Component",
            "component's `type`",
        ),
        (
            "InteractionType",
            "interaction data",
            "INTERACTION_DATA_BY_TYPE",
            INTERACTION_DATA,
            "",
            "interaction's `type`",
        ),
        (
            "InteractionCallbackType",
            "callback data",
            "CALLBACK_DATA_BY_TYPE",
            CALLBACK_DATA,
            "",
            "callback's `type`",
        ),
    ):
        rows = table(enum_name, label, lookup)
        if not rows:
            continue
        used.update(name for _, _, name in rows)
        used.add(enum_name)
        entries = "".join(f"    {enum_name}.{member}: {target},\n" for member, _, target in rows)
        blocks.append(
            f"{const}: dict[int, type] = {{\n{entries}}}\n"
            f'"""The class modelling the data of each {doc} value."""'
        )
        if alias:
            members = " | ".join(dict.fromkeys(target for _, _, target in rows))
            blocks.append(f'{alias}: TypeAlias = {members}\n"""Any {label} class."""')
    by_module: dict[str, list[str]] = {}
    for name in sorted(used):
        by_module.setdefault(owner[name], []).append(name)
    imports = "".join(
        f"from {mod} import {', '.join(names)}\n" for mod, names in sorted(by_module.items())
    )
    header = dedent(f'''\
        """Classes by component type and by interaction type.

        {GENERATED_MARKER}. Do not edit by hand.
        """

        from __future__ import annotations

        from typing import TypeAlias

        ''')
    helpers = dedent('''\
        def decode_by_type(table: Mapping[int, type], data: Mapping[str, Any]) -> Any:  # noqa: ANN401
            """Build the class `table` holds for `data["type"]`; unknown types stay dicts."""
            kind = data.get("type")
            cls = table.get(kind) if isinstance(kind, int) else None
            return from_dict(cls, data) if cls else data


        def decode_component(data: Mapping[str, Any]) -> Any:  # noqa: ANN401
            """Build the component class that `data["type"]` names."""
            return decode_by_type(COMPONENT_BY_TYPE, data)
        ''')
    body = "\n\n".join(blocks)
    return f"{header}from collections.abc import Mapping\nfrom typing import Any\n\nfrom dispyre.decode import from_dict\n{imports}\n\n{body}\n\n\n{helpers}"


