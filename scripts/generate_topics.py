def rate_limit_items(markdown: str, registry: Registry, plan: Plan) -> None:
    """Add the `X-RateLimit-*` headers and scopes, and the limits stated in the prose."""
    headers: list[Member] = []
    scope_note = ""
    for line in markdown.splitlines():
        if match := HEADER_BULLET.match(line):
            wire, doc = match.group(1), plain(match.group(2))
            headers.append(Member(constant(wire.removeprefix("X-RateLimit-")), repr(wire), doc))
            if wire.endswith("Scope"):
                scope_note = match.group(2)
    if headers:
        table = fake_table(RATE_LIMITS, "Rate Limit Headers", "header-format")
        plan.add(
            RATE_LIMITS, Enum(registry.claim("RateLimitHeader", table), "StrEnum", table, headers)
        )
    scopes = [
        Member(constant(value), repr(value), plain(doc))
        for value, doc in SCOPE_VALUE.findall(scope_note)
    ]
    if scopes:
        table = fake_table(RATE_LIMITS, "Rate Limit Scopes", "header-format")
        plan.add(
            RATE_LIMITS, Enum(registry.claim("RateLimitScope", table), "StrEnum", table, scopes)
        )
    tail = []
    if match := LIMIT_PER_SECOND.search(markdown):
        tail.append(
            f'GLOBAL_REQUESTS_PER_SECOND = {match.group(1)}\n"""Requests a bot may make per second."""'
        )
    if match := INVALID_LIMIT.search(markdown):
        tail.append(
            f"INVALID_REQUEST_LIMIT = {match.group(1).replace(',', '')}\n"
            f'"""Invalid requests (401, 403, 429) allowed per window before an IP is blocked."""'
        )
        tail.append(
            f'INVALID_REQUEST_WINDOW_MINUTES = {match.group(2)}\n"""Length of that window."""'
        )
    plan.tails.setdefault(RATE_LIMITS, []).extend(tail)


def json_examples(markdown: str) -> list[tuple[str, dict[str, Any]]]:
    """Every parseable JSON object in a ```json block, with the closest heading above it."""
    found: list[tuple[str, dict[str, Any]]] = []
    title, body, inside = "", [], False
    for line in markdown.splitlines():
        if line.lstrip().startswith("```"):
            if inside:
                text = re.sub(r"\s//.*$|^\s*//.*$", "", "\n".join(body), flags=re.MULTILINE)
                try:
                    data = json.loads(text)
                except json.JSONDecodeError:
                    try:  # "[ ...251, 100, 11...]" elides array items
                        data = json.loads(text.replace("...", ""))
                    except json.JSONDecodeError:
                        data = None
                if isinstance(data, dict):
                    found.append((title, data))
                body = []
            inside = not inside and line.lstrip().startswith("```json")
        elif inside:
            body.append(line)
        elif match := HEADING.match(line):
            title = plain(match.group(2))
    return found


def infer(value: Any, key: str) -> str:  # noqa: ANN401
    """Annotation for a JSON example value; ids sent as digit strings are snowflakes."""
    if isinstance(value, bool):
        return "bool"
    if isinstance(value, int):
        return "int"
    if isinstance(value, float):
        return "float"
    if isinstance(value, str):
        return "Snowflake" if value.isdigit() and key.endswith("id") else "str"
    if isinstance(value, list):
        return f"list[{infer(value[0], key)}]" if value else "list[Any]"
    return "dict[str, Any]"


@dataclass
class ExampleModel:
    """Fields merged from every example that names the same payload."""

    name: str
    page: str
    anchor: str
    op: int | None = None
    fields: dict[str, tuple[str, int]] = field(default_factory=dict)
    seen: int = 0
    nested: dict[str, dict[str, Any]] = field(default_factory=dict)


def example_name(title: str) -> str:
    text = re.sub(r"^Example\s+|\s+Payload$", "", EXAMPLE_VERSION.sub("", title))
    text = re.sub(r"\s+Payload\b", "", text)
    return pascal(text if text.lower().startswith("voice") else f"Voice {text}")


def voice_payloads(markdown: str, registry: Registry, plan: Plan) -> None:
    """Add a model per voice opcode payload, from the JSON examples, plus `VOICE_PAYLOADS`."""
    merged: dict[str, ExampleModel] = {}
    scalar_payloads: dict[int, list[str]] = {}
    for title, example in json_examples(markdown):
        op, data = example.get("op"), example.get("d")
        if (
            not title.startswith("Example")
            or not isinstance(op, int)
            or any(skip in title for skip in SKIPPED_EXAMPLES)
        ):
            continue
        if not isinstance(data, dict) or not all(key.isidentifier() for key in data):
            # A scalar, null, or a map keyed by ssrc such as {"any": 100, "2": 50}.
            kind = "None" if data is None else infer(data, "d")
            if isinstance(data, dict):
                kind = f"dict[str, {infer(next(iter(data.values())), 'd')}]"
            scalar_payloads.setdefault(op, [])
            if kind not in scalar_payloads[op]:
                scalar_payloads[op].append(kind)
            continue
        model = merged.setdefault(
            example_name(title), ExampleModel(example_name(title), VOICE, slug(title), op)
        )
        model.seen += 1
        for key, value in data.items():
            if isinstance(value, dict) and value:
                model.nested[key] = value
                annotation = pascal(f"{model.name} {key}")
            else:
                annotation = infer(value, key)
            previous, count = model.fields.get(key, (annotation, 0))
            model.fields[key] = (previous, count + (value is not None))
    ops_to_models: dict[int, list[str]] = {}
    for model in merged.values():
        name = registry.claim(model.name, fake_table(VOICE, model.name))
        table = Table(VOICE, model.name, "", [model.anchor], [], [], [])
        item = Model(name, table)
        for key, (annotation, count) in model.fields.items():
            optional = count < model.seen
            if key in model.nested:
                nested = registry.claim(annotation, fake_table(VOICE, key))
                inner = Model(nested, table)
                for sub_key, sub_value in model.nested[key].items():
                    inner.fields.append(Field(sub_key, infer(sub_value, sub_key), False, ""))
                plan.add(VOICE, inner)
                annotation = nested
            if optional:
                annotation += " | None"
            item.fields.append(Field(key, annotation, optional, ""))
        plan.add(VOICE, item)
        if model.op is not None:
            ops_to_models.setdefault(model.op, []).append(name)
    for op, kinds in scalar_payloads.items():
        ops_to_models.setdefault(op, []).extend(kinds)
    envelope = Model(
        registry.claim("VoicePayload", fake_table(VOICE, "Voice Payload")),
        fake_table(VOICE, "Voice Payload"),
        fields=[
            Field("op", "int", False, "Voice opcode."),
            Field("d", "Any", False, "Payload; see `VOICE_PAYLOADS` for its type per opcode."),
            Field("seq", "int | None", True, "Sequence number, sent by the server since V8."),
        ],
    )
    plan.items[VOICE].insert(0, envelope)
    plan.tails[VOICE] = [
        "VOICE_PAYLOADS: dict[int, tuple[Any, ...]] = {\n"
        + "".join(
            f"    {op}: ({', '.join(names)}{',' if len(names) == 1 else ''}),\n"
            for op, names in sorted(ops_to_models.items())
        )
        + "}\n"
        '"""Payload types for each voice opcode, as the docs show them. An opcode listed more than\n'
        'once is sent in both directions, or changed shape between gateway versions."""',
    ]


def inner_payload_links(markdown: str, title: str) -> list[tuple[str, str]]:
    """Links in the "The inner payload is ..." sentence under the event's `#### title`."""
    lines = markdown.splitlines()
    start = next((i for i, line in enumerate(lines) if line.strip() == f"#### {title}"), None)
    if start is None:
        return []
    for line in lines[start + 1 :]:
        if line.startswith("#### "):
            break
        if line.lower().startswith("the inner payload"):
            return LINK.findall(line)
    return []


def webhook_payloads(
    per_page: dict[str, list[Item]], markdown: str, registry: Registry, plan: Plan
) -> None:
    """Map each webhook event type to the class its section describes.

    The class is the model named after the event, else whatever the section's "The inner
    payload is a [..] object" sentence links to (a resource, or a model on the same page).
    """
    items = per_page.get(WEBHOOKS, [])
    types = next((i for i in items if isinstance(i, Enum) and i.name == "WebhookEventType"), None)
    models = {i.name for i in items if isinstance(i, Model)}
    if types is None:
        plan.notes.append("webhook event types table not found")
        return
    rows = []
    for member in types.members:
        title = next(
            (
                plain(r[0])
                for r in types.table.rows
                if plain(r[1]).strip("`") == member.value.strip("'")
            ),
            "",
        )
        payload = next((c for c in (pascal(title),) if c in models), "")
        if not payload:
            found = [
                resolve_link(label, url, WEBHOOKS, registry)
                for label, url in inner_payload_links(markdown, title)
            ]
            payload = " | ".join(dict.fromkeys(name for name in found if name))
        if not payload:
            payload = "dict[str, Any]"
            plan.notes.append(
                f"webhook {member.value}: no payload class found; typed dict[str, Any]"
            )
        rows.append(f"    WebhookEventType.{member.name}: {payload},\n")
    plan.tails[WEBHOOKS] = [
        "WEBHOOK_EVENT_PAYLOADS: dict[WebhookEventType, Any] = {\n" + "".join(rows) + "}\n"
        '"""The payload class for each webhook event type (the `data` of a `WebhookEventBody`)."""'
    ]


def merge_spec_scopes(per_page: dict[str, list[Item]], spec: dict[str, Any], plan: Plan) -> None:
    """Add the OAuth2 scopes the OpenAPI spec lists and the docs table lacks.

    The spec is the more complete source (it has `openid`, `rpc.video.*` and others), so the
    enum is the docs' table plus every spec scope it misses, with the spec's description.
    """
    scheme = spec.get("components", {}).get("securitySchemes", {}).get("OAuth2", {})
    scopes: dict[str, str] = {}
    for flow in scheme.get("flows", {}).values():
        scopes.update(flow.get("scopes", {}))
    enum = next(
        (i for i in per_page.get(OAUTH2, []) if isinstance(i, Enum) and i.name == "OAuth2Scope"),
        None,
    )
    if enum is None:
        plan.notes.append("OAuth2 scopes table not found; the spec's scopes were not added")
        return
    known = {member.value.strip("'") for member in enum.members}
    for scope, doc in sorted(scopes.items()):
        if scope not in known:
            enum.members.append(Member(constant(scope), repr(scope), doc))
            plan.notes.append(f"OAuth2 scope {scope!r} comes from the OpenAPI spec only")


