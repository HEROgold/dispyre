@dataclass
class Plan:
    """Everything the run generates, per docs page, plus the tails that tie items together."""

    items: dict[str, list[Item]] = field(default_factory=dict)
    tails: dict[str, list[str]] = field(default_factory=dict)
    skipped: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def add(self, page: str, item: Item) -> None:
        self.items.setdefault(page, []).append(item)


def module_of(page: str) -> str:
    """`topics/rate-limits` -> `rate_limits`; `events/webhook-events` -> `webhook_events`."""
    return page.rpartition("/")[2].replace("-", "_")


def fake_table(page: str, heading: str, anchor: str = "") -> Table:
    """Return a stand-in for a docs table, so generated classes link to the right anchor."""
    return Table(page, heading, "", [anchor or slug(heading)], [], [], [])


