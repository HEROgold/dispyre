#!/usr/bin/env python3
"""Generate enums, models and registries from Discord's topic, reference and webhook pages.

Pages (see `docgen.py` for how they are fetched and parsed):

- `topics/opcodes-and-status-codes`: gateway, voice and RPC opcodes and close codes, HTTP
  status codes and JSON error codes, as `IntEnum`s.
- `topics/voice-connections`: the encryption modes and speaking flags from its tables, and a
  payload model per voice opcode, inferred from the page's JSON examples (the page has no
  field tables for them).
- `topics/rate-limits`: the header names, the scopes and the limits quoted in the prose.
- `reference`: the locales (and the nullable/optional notes).
- `topics/oauth2`: the scopes. `topics/rpc` and `topics/certified-devices`: the RPC commands,
  events and payload models.
- `events/webhook-events`: the event types, the payload models and the type -> payload table.

`unions.py` ties the component types and interaction types of the resource pages to the
classes that model their data, for the unions the docs describe only in prose.

Output goes to `src/dispyre/discord/topics/`. The resource models these build on come from
`scripts/generate_resources.py`, so run that first (or let this one reuse its cached pages).

Usage:
    uv run scripts/generate_topics.py            # fetch, cache and generate
    uv run scripts/generate_topics.py --offline  # regenerate from the cache only
"""

