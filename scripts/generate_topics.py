def generate(*, offline: bool) -> None:
    resource_pages = load_pages(offline=offline, only=None, depth=2)
    topic_pages = {page: md for page in PAGES if (md := load_page(page, offline=offline))}
    if len(topic_pages) != len(PAGES):
        msg = f"topic pages missing from the cache: {sorted(set(PAGES) - topic_pages.keys())}"
        raise SystemExit(msg)

    registry = Registry()
    resource_items, resource_models, _ = collect(
        resource_pages, registry, overrides=RESOURCE_OVERRIDES
    )
    for model in resource_models:
        build_model(model, registry)
    add_partials(resource_items, registry)
    owner = {
        item.name: f"{RESOURCES_PACKAGE}.{module_name(page)}"
        for page, items in resource_items.items()
        for item in items
    }

    plan = Plan()
    per_page, models, skipped = collect(
        topic_pages,
        registry,
        overrides=OVERRIDES,
        renames=RENAMES,
        enums_only=set(resource_pages),
    )
    plan.skipped.extend(skipped)
    for model in models:
        build_model(model, registry)
    known = set(registry.partials)
    add_partials(per_page, registry)
    plan.items = per_page
    rate_limit_items(topic_pages[RATE_LIMITS], registry, plan)
    voice_payloads(topic_pages[VOICE], registry, plan)
    webhook_payloads(per_page, topic_pages[WEBHOOKS], registry, plan)
    merge_spec_scopes(per_page, load_spec(offline=offline), plan)
    del known
    for page, items in plan.items.items():
        owner.update({item.name: f"{PACKAGE}.{module_of(page)}" for item in items})
    unions = render_unions(resource_items, owner, plan)
    write_output(plan, owner, unions)
    report(plan, registry)


def write_output(plan: Plan, owner: dict[str, str], unions: str) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    exports: dict[str, list[str]] = {}
    written = {OUTPUT_DIR / "__init__.py", OUTPUT_DIR / "unions.py"}
    for page, items in plan.items.items():
        tails = plan.tails.get(page, [])
        if not items and not tails:
            continue
        path = OUTPUT_DIR / f"{module_of(page)}.py"
        path.write_text(render_page(page, items, owner, tails), "utf-8")
        written.add(path)
        names = {item.name for item in items}
        names.update(re.findall(r"^([A-Z][A-Z_]+)\b", "\n".join(tails), re.MULTILINE))
        exports[module_of(page)] = sorted(names)
    (OUTPUT_DIR / "unions.py").write_text(unions, "utf-8")
    exports["unions"] = [
        n
        for n in re.findall(r"^([A-Za-z_]\w*)(?::|\s*=)", unions, re.MULTILINE)
        if n.isupper() or n == "Component"
    ] + ["decode_by_type", "decode_component"]
    (OUTPUT_DIR / "__init__.py").write_text(render_init(exports), "utf-8")
    for path in OUTPUT_DIR.glob("*.py"):
        if path not in written and GENERATED_MARKER in path.read_text("utf-8")[:500]:
            print(f"removing stale {path.name}")
            path.unlink()
    ruff = ["uv", "run", "ruff"]
    subprocess.run([*ruff, "check", "--fix", "--quiet", str(OUTPUT_DIR)], check=False)
    subprocess.run([*ruff, "format", "--quiet", str(OUTPUT_DIR)], check=True)


def report(plan: Plan, registry: Registry) -> None:
    items = [i for page_items in plan.items.values() for i in page_items]
    print(
        f"\n{len(plan.items)} pages: {sum(isinstance(i, Enum) for i in items)} enums, "
        f"{sum(isinstance(i, Model) for i in items)} models -> {OUTPUT_DIR}"
    )
    for line in plan.skipped:
        print(f"skipped {line}")
    for line in plan.notes:
        print(f"note: {line}")
    if registry.unresolved:
        print(
            f"\n{sum(registry.unresolved.values())} unresolved types (emitted as Any / dict[str, Any]):"
        )
        for text, count in sorted(registry.unresolved.items(), key=lambda kv: -kv[1]):
            print(f"  {count:3}x  {text}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offline", action="store_true", help="only use cached pages")
    generate(offline=parser.parse_args().offline)


if __name__ == "__main__":
    main()
