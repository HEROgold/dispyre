#!/usr/bin/env python3
"""Crawl Discord's gateway docs and generate the gateway event models.

Reads two pages as raw markdown (see `docgen.py`):

- `events/gateway-events` lists every send and receive event. Each event becomes a
  payload model, a subclass of a resource model (when the docs say "the inner payload
  is a [guild] object with extra fields"), or an alias of a resource model. Footnotes
  under a table and the `Default` / `Required` columns end up in the field docs.
- `events/gateway` lists the intents and the events each one enables.

Output goes to `src/dispyre/discord/events/`:

- `gateway_events.py`: the payload models, their enums and one exported name per event.
- `gateway.py`: `GatewayIntents`.
- `registry.py`: `SendEvent`, `ReceiveEvent` and an `EventInfo` per event.
- `tests/fixtures/gateway_event_examples.json`: the docs' JSON examples, which the
  tests decode into the models.

The resource models the events build on come from `scripts/generate_resources.py`, so
run that script first (or let this one reuse its cached pages).

Usage:
    uv run scripts/generate_gateway_events.py            # fetch, cache and generate
    uv run scripts/generate_gateway_events.py --offline  # regenerate from the cache only
"""

