GENERATED_MARKER = "Generated by `scripts/generate_gateway_events.py`"

# Objects the docs show only as a JSON example, with no field table. The fields come from the
# example: `id` is required, every other key is optional.
EXAMPLE_ONLY_OBJECTS = {("resources/guild", "Unavailable Guild Object"): "UnavailableGuild"}

# Tables that would get an awkward name from their heading.
NAME_OVERRIDES = {"Payload Structure": "GatewayEventPayload"}

LINK_MD = r"\[[^\]]+\]\([^)]*\)"
INNER_PAYLOAD = re.compile(
    rf"inner payload is (?:an?|the)\s+({LINK_MD})(?:\s+object)?", re.IGNORECASE
)
SUBSET = re.compile(
    rf"inner payload is a subset of the ({LINK_MD}) object, containing just the (.*?) fields",
    re.IGNORECASE,
)
OMITTED = re.compile(r"with `(\w+)` omitted")
SAME_EXTRA = re.compile(r"same extra fields as \[[^\]]*\]\([^)]*#([a-z0-9-]+)\)", re.IGNORECASE)
CALLOUT = re.compile(r"^\[!(\w+)\]$")
TRAILING_MARKS = re.compile(r"((?:\\?\*)+)\s*$")
INTENT_LINE = re.compile(r"^([A-Z_]+) \(1 << (\d+)\)\s*((?:\*)*)$")
INTENT_EVENT = re.compile(r"^\s+- ([A-Z_]+)\s*((?:\*)*)$")
FOOTNOTE_LINE = re.compile(r"^((?:\\\*)+)\s+(.+)$")
# Code points of the typographic characters the docs use, and their ASCII stand-ins.
ASCII = {
    0x2018: "'",  # left single quotation mark
    0x2019: "'",  # right single quotation mark
    0x201C: '"',  # left double quotation mark
    0x201D: '"',  # right double quotation mark
    0x2013: "-",  # en dash
    0x2014: " - ",  # em dash
    0x2026: "...",  # horizontal ellipsis
    0x00A0: " ",  # no-break space
}


@dataclass
class EventModel(Model):
    """A payload class, optionally extending a resource model."""

    base: str = ""
    paragraphs: list[str] = field(default_factory=list)
    source: str = ""
    """Anchor of the event this class is the payload of, if any."""
    overrides: set[str] = field(default_factory=set)
    """Fields that redeclare a base field with another type, which type checkers flag."""


@dataclass
class EventDef:
    """One event from the summary tables, with what its section says about it."""

    title: str
    description: str
    direction: str
    category: str = ""
    intro: list[str] = field(default_factory=list)
    callouts: list[tuple[str, str]] = field(default_factory=list)
    tables: list[Table] = field(default_factory=list)
    op: int | None = None
    example: dict[str, Any] | None = None
    kind: str = "none"
    base: str = ""
    omit: list[str] = field(default_factory=list)
    keep: list[str] = field(default_factory=list)
    union: list[str] = field(default_factory=list)
    same_as: str = ""
    literal: str = "None"
    export: str = ""
    intents: list[str] = field(default_factory=list)

    @property
    def slug(self) -> str:
        """The heading anchor, as in links to the event."""
        return slug(self.title)

    @property
    def wire(self) -> str:
        """The event's name on the wire: `Channel Create` is `CHANNEL_CREATE`."""
        return re.sub(r"\W+", "_", self.title).strip("_").upper()

    @property
    def primary(self) -> Table | None:
        """The first field table in the event's section, which describes its payload."""
        return next((table for table in self.tables if is_model_table(table)), None)

    @property
    def text(self) -> str:
        """The prose before the event's first table or sub-heading."""
        return "\n".join(self.intro)


@dataclass
class Intent:
    """One gateway intent and the events it enables."""

    name: str
    bit: int
    marks: int
    events: list[tuple[str, int]] = field(default_factory=list)


# --- reading the docs ---------------------------------------------------------


def parse_events(markdown: str) -> tuple[dict[str, EventDef], list[Table]]:
    """Return the events keyed by anchor, plus every table on the page."""
    tables = parse_tables(EVENTS_PAGE, markdown)
    events: dict[str, EventDef] = {}
    for table in tables:
        if table.header == ["Name", "Description"] and table.heading in {
            "Send Events",
            "Receive Events",
        }:
            direction = table.heading.split()[0].lower()
            for row in table.rows:
                event = EventDef(plain(row[0]), plain(row[1]), direction)
                events[event.slug] = event
    read_sections(markdown, events)
    titles = {event.title: event for event in events.values()}
    for table in tables:
        owner = titles.get(table.heading) or titles.get(table.container)
        if owner:
            owner.tables.append(table)
    return events, tables


def read_sections(markdown: str, events: dict[str, EventDef]) -> None:
    """Fill each event's prose, callouts and example from the lines of its section."""
    sections: dict[str, list[str]] = {}
    current: str | None = None
    category = ""
    in_fence = False
    for line in markdown.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        heading = None if in_fence else HEADING.match(line)
        if heading and len(heading.group(1)) <= 4:  # noqa: PLR2004
            level, title = len(heading.group(1)), plain(heading.group(2))
            current = slug(title) if slug(title) in events else None
            if current:
                events[current].category = category
                sections[current] = []
            elif level == 2:  # noqa: PLR2004
                category = "Send" if "send" in title.lower() else "Connection"
            elif level == 3:  # noqa: PLR2004
                category = title
            continue
        if current:
            sections[current].append(line)
    for key, lines in sections.items():
        read_section(events[key], lines)


def read_section(event: EventDef, lines: list[str]) -> None:
    prose: list[str] = []
    for line in lines:
        if line.startswith(("#", "|", "```")):
            break
        if not line.startswith(">"):
            prose.append(line)
    event.intro = [p.strip() for p in re.split(r"\n\s*\n", "\n".join(prose)) if p.strip()]
    block: list[str] = []
    for line in [*lines, ""]:
        if line.startswith(">"):
            block.append(line.removeprefix(">").strip())
            continue
        kind = CALLOUT.match(block[0]) if block else None
        if kind:
            text = " ".join(part for part in block[1:] if part)
            event.callouts.append((kind.group(1).title(), text))
        block = []
    read_example(event, lines)


def read_example(event: EventDef, lines: list[str]) -> None:
    """Parse the section's first JSON example, which is a whole gateway payload."""
    body: list[str] = []
    inside = False
    for line in lines:
        if line.lstrip().startswith("```"):
            if inside:
                break
            inside = line.lstrip().startswith("```json")
        elif inside:
            body.append(line)
    text = re.sub(r"\s//.*$|^\s*//.*$", "", "\n".join(body), flags=re.MULTILINE)
    if not text.strip():
        return
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        print(f"unparseable example in {event.title}")
        return
    if isinstance(data, dict):
        event.example = data
        op = data.get("op")
        event.op = op if isinstance(op, int) else None
        d = data.get("d")
        if isinstance(d, bool):
            event.literal = "bool"
        elif isinstance(d, int):
            event.literal = "int | None"


def example_models(pages: dict[str, str], registry: Registry) -> list[EventModel]:
    """Build the `EXAMPLE_ONLY_OBJECTS` from the JSON example under their headings."""
    models: list[EventModel] = []
    for (page, heading), name in EXAMPLE_ONLY_OBJECTS.items():
        markdown = pages.get(page, "")
        start = markdown.find(f"### {heading}")
        fence = markdown.find("```json", start)
        body = markdown.find("\n", fence) + 1
        end = markdown.find("```", body)
        data = json.loads(markdown[body:end]) if start >= 0 and fence > start else None
        if not isinstance(data, dict):
            print(f"no JSON example under {heading!r} in {page}")
            continue
        table = Table(page, heading, "", [slug(heading)], [], [], [])
        model = EventModel(registry.claim(name, table), table)
        for key, value in data.items():
            annotation = {bool: "bool", int: "int", float: "float"}.get(type(value), "str")
            if isinstance(value, str) and value.isdigit():
                annotation = "Snowflake"
            model.fields.append(
                Field(key, annotation if key == "id" else f"{annotation} | None", key != "id", "")
            )
        intro = f"{heading.removesuffix(' Object')}. The docs show this object only as an example."
        model.paragraphs = [intro, f"{DOCS_ROOT}/developers/{page}#{slug(heading)}"]
        registry.register(model.name, table)
        models.append(model)
    return models


def parse_intents(markdown: str) -> list[Intent]:
    """Read the `List of Intents` block, which names each intent, its bit and its events."""
    start = markdown.find("### List of Intents")
    fence = markdown.find("```", start)
    end = markdown.find("```", fence + 3)
    intents: list[Intent] = []
    for line in markdown[fence:end].splitlines():
        if match := INTENT_LINE.match(line):
            intents.append(Intent(match.group(1), int(match.group(2)), len(match.group(3))))
        elif (match := INTENT_EVENT.match(line)) and intents:
            intents[-1].events.append((match.group(1), len(match.group(2))))
    return intents


def intent_notes(markdown: str) -> dict[int, str]:
    r"""Return the `\\*` footnotes that follow the intents list, keyed by asterisk count."""
    start = markdown.find("### List of Intents")
    fence = markdown.find("```", start)
    after = markdown.find("```", fence + 3) + 3
    notes: dict[int, str] = {}
    for line in markdown[after:].splitlines():
        if match := FOOTNOTE_LINE.match(line.strip()):
            notes[match.group(1).count("\\*")] = plain(match.group(2))
        elif line.startswith("#"):
            break
    return notes


# --- planning: what each event becomes ---------------------------------------


def link_class(link: str, registry: Registry) -> str | None:
    match = LINK.search(link)
    return resolve_link(match.group(1), match.group(2), EVENTS_PAGE, registry) if match else None


def classify(event: EventDef, registry: Registry) -> None:
    """Decide from the event's prose and tables whether it is a model, a subclass or an alias."""
    text = event.text
    primary = event.primary
    if "inner payload can be" in text.lower():
        event.kind = "union"
        for line in (line for line in text.splitlines() if line.lstrip().startswith("*")):
            name = link_class(line, registry)
            if name and "extra fields" in line.lower():
                event.base = name
            elif name:
                event.union.append(name)
    elif subset := SUBSET.search(text):
        event.kind = "subset"
        event.base = link_class(subset.group(1), registry) or ""
        event.keep = re.findall(r"`(\w+)`", subset.group(2))
    elif inner := INNER_PAYLOAD.search(text):
        event.base = link_class(inner.group(1), registry) or ""
        if same := SAME_EXTRA.search(text):
            event.kind, event.same_as = "alias_event", same.group(1)
        elif primary and re.search(r"extra|additional", primary.heading, re.IGNORECASE):
            event.kind = "subclass"
            event.omit = OMITTED.findall(text)
        else:
            event.kind = "alias"
    elif primary:
        event.kind = "model"
    else:
        event.kind = "literal"


def claim(registry: Registry, name: str) -> str:
    """Reserve a class name, adding `Event` until it is unique."""
    while name in registry.names:
        name += "Event"
    registry.names.add(name)
    return name


def register_event(registry: Registry, event: EventDef, name: str, table: Table | None) -> None:
    """Point the event's anchor, and its table's anchors, at `name`."""
    anchors = [event.slug, *(table.anchors if table else [])]
    for anchor in anchors:
        registry.by_anchor.setdefault((EVENTS_PAGE, anchor), (EVENTS_PAGE, name))


@dataclass
class Plan:
    """Every class this run generates, in document order."""

    items: list[Item] = field(default_factory=list)
    late: list[Item] = field(default_factory=list)
    aliases: list[tuple[str, str, str]] = field(default_factory=list)  # name, expression, doc
    models: list[EventModel] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)


def plan_events(events: dict[str, EventDef], tables: list[Table], registry: Registry) -> Plan:
    plan = Plan()
    for event in events.values():
        classify(event, registry)
        name = pascal(event.title)
        if event.kind in {"model", "subclass", "union"}:
            claimed = claim(registry, name)
            table = event.primary
            item = EventModel(
                claimed,
                table or tables[0],
                base=event.base if event.kind != "model" else "",
                source=event.slug,
            )
            if event.kind == "subclass" and event.omit:
                item.base = ""  # flat copy, so the omitted fields really are gone
            event.export = claimed
            register_event(registry, event, claimed, table)
            plan.models.append(item)
            plan.items.append(item)
            if event.kind == "union":
                payload = claim(registry, f"{name}Payload")
                members = [claimed, *event.union]
                plan.aliases.append((payload, " | ".join(members), event.description))
                event.export = payload
        elif event.kind == "subset":
            claimed = claim(registry, name)
            item = EventModel(
                claimed,
                Table(EVENTS_PAGE, event.title, "", [event.slug], [], [], []),
                source=event.slug,
            )
            event.export = claimed
            register_event(registry, event, claimed, None)
            plan.models.append(item)
            plan.late.append(item)
    for event in events.values():
        if event.kind in {"alias", "alias_event"}:
            target = event.base if event.kind == "alias" else events[event.same_as].export
            if not target:
                print(f"unresolved payload for {event.title}: {event.text[:80]!r}")
                event.kind, event.literal = "literal", "dict[str, Any]"
                continue
            event.export = claim(registry, pascal(event.title))
            registry.by_anchor.setdefault((EVENTS_PAGE, event.slug), (EVENTS_PAGE, target))
            plan.aliases.append((event.export, target, event.description))
    plan_tables(events, tables, registry, plan)
    return plan


def plan_tables(
    events: dict[str, EventDef], tables: list[Table], registry: Registry, plan: Plan
) -> None:
    """Name every other table on the page: supporting models and enums."""
    primaries = {
        id(event.primary)
        for event in events.values()
        if event.kind in {"model", "subclass", "union"}
    }
    order = {id(table): index for index, table in enumerate(tables)}
    for table in tables:
        if id(table) in primaries or table.header[:2] == ["Name", "Description"]:
            continue
        if is_model_table(table):
            base = NAME_OVERRIDES.get(table.heading) or pascal(strip_suffix(table.heading))
            name = claim(registry, base)
            registry.register(name, table)
            registry.models.add(name)
            item = EventModel(name, table)
            plan.models.append(item)
        elif columns := enum_columns(table):
            built = build_enum(table, columns, registry) or build_computed(table, columns, registry)
            if built is None:
                plan.skipped.append(f"{plain(table.heading)} (unparseable values)")
                continue
            registry.register(built.name, table)
            item = built
        else:
            plan.skipped.append(f"{plain(table.heading)} (not a model or enum table)")
            continue
        plan.items.append(item)
    plan.items.sort(key=lambda item: order.get(id(item.table), len(tables)))


def build_models(
    plan: Plan, events: dict[str, EventDef], registry: Registry, resources: dict[str, Model]
) -> None:
    """Pass 2: resolve field types, then fold footnotes, defaults and base fields in."""
    local = {item.name: item for item in plan.models}
    for model in plan.models:
        if model.table.rows:
            build_model(model, registry)
            apply_notes(model, registry)
    for model in plan.models:
        event = events.get(model.source)
        if event is not None:
            attach_base(model, event, resources | local)
            model.paragraphs = event_paragraphs(event)
        else:
            model.paragraphs = [
                f"{plain(model.table.heading)}.",
                source_line(model.table.anchors[-1]),
            ]


def attach_base(model: EventModel, event: EventDef, known: dict[str, Model]) -> None:
    base = known.get(event.base)
    if event.kind == "subset" and base:
        model.fields = [f for f in base.fields if f.name in event.keep]
    elif event.kind == "subclass" and event.omit and base:
        kept = [f for f in base.fields if f.name not in event.omit]
        model.fields = [*kept, *model.fields]
    elif base:
        inherited = {f.name: f.annotation for f in base.fields}
        model.overrides = {
            f.name
            for f in model.fields
            if f.name in inherited and inherited[f.name] != f.annotation
        }


def star_count(cell: str) -> int:
    match = TRAILING_MARKS.search(cell.strip())
    return match.group(1).count("*") if match else 0


def apply_notes(model: Model, registry: Registry) -> None:
    """Add footnotes, `Default` and `Required` cells to each field's doc.

    The description and each addition are separate paragraphs, split by a blank line.
    A field typed `object` takes the class its description links to, if there is one.
    """
    table = model.table
    default_col, required_col = column(table, "default"), column(table, "required")
    desc_col = column(table, "description")
    fields = {f.name: f for f in model.fields}
    for row in table.rows:
        if len(row) < 2 or not plain(row[0]):  # noqa: PLR2004
            continue
        name = identifier(plain(row[0]).rstrip("*").strip().rstrip("?"))
        target = fields.get(name)
        if target is None:
            continue
        extras = [
            f"Note: {table.footnotes[mark]}"
            for mark in sorted({star_count(cell) for cell in row[:3]})
            if mark in table.footnotes
        ]
        for col, label in ((default_col, "Default"), (required_col, "Required")):
            value = plain(row[col]) if col is not None and len(row) > col else ""
            if value and value != "-":
                extras.append(f"{label}: {value}.")
        target.doc = "\n\n".join([re.sub(r"\s*\*+$", "", target.doc), *extras]).strip()
        if desc_col is not None and plain(row[1]).lower() == "object":
            linked = link_class(row[desc_col], registry)
            if linked and target.annotation.startswith("dict[str, Any]"):
                target.annotation = target.annotation.replace("dict[str, Any]", linked)


def make_partials(
    plan: Plan, registry: Registry, resources: dict[str, Model], known: set[str]
) -> None:
    """Generate `PartialX` for models the events use that the resources don't already have."""
    local = {item.name: item for item in plan.models}
    for base in sorted(registry.partials - known):
        source = local.get(base) or resources.get(base)
        if source is None:
            continue
        name = claim(registry, f"Partial{base}")
        partial = EventModel(name, source.table, partial_of=base)
        for f in source.fields:
            annotation = (
                f.annotation if f.annotation.endswith(" | None") else f"{f.annotation} | None"
            )
            partial.fields.append(Field(f.name, annotation, optional=True, doc=f.doc))
        partial.paragraphs = [f"Partial {base}: the same fields, any of which may be missing."]
        plan.models.append(partial)
        plan.items.append(partial)


# --- rendering ---------------------------------------------------------------


def ascii_text(text: str) -> str:
    return text.translate(ASCII)


def source_line(anchor: str) -> str:
    return f"{DOCS_ROOT}/developers/{EVENTS_PAGE}#{anchor}"


def event_paragraphs(event: EventDef) -> list[str]:
    """Class docstring paragraphs: summary, the docs' prose, callouts, wire name, link."""
    description = event.description.rstrip(".") + "."
    paragraphs = [description]
    paragraphs.extend(prose(p) for p in event.intro if plain(p).rstrip(".") != description[:-1])
    paragraphs.extend(f"{kind}: {plain(text)}" for kind, text in event.callouts)
    op = f", opcode {event.op}" if event.op is not None else ""
    paragraphs.append(f"{event.direction.title()} event `{event.wire}`{op}.")
    paragraphs.append(source_line(event.slug))
    return paragraphs


LIST_ITEM = re.compile(r"^(?:[*-]|\d+\.)\s+")


def prose(raw: str) -> str:
    """Markdown paragraph to plain text; list items stay on their own lines as `- item`."""
    lines: list[str] = []
    buffer: list[str] = []
    for line in plain(raw).splitlines():
        line = line.strip()
        if LIST_ITEM.match(line):
            if buffer:
                lines.append(" ".join(buffer))
                buffer = []
            lines.append(re.sub(r"^\*\s+", "- ", line))
        elif line:
            buffer.append(line)
    if buffer:
        lines.append(" ".join(buffer))
    return "\n".join(lines)


def wrap_paragraph(text: str, width: int) -> str:
    """Wrap each line of a paragraph; list items get a hanging indent."""
    lines = []
    for line in text.splitlines():
        hanging = "  " if LIST_ITEM.match(line) else ""
        lines.extend(
            wrap(
                line,
                width,
                subsequent_indent=hanging,
                break_long_words=False,
                break_on_hyphens=False,
            )
        )
    return "\n".join(lines)


def block_doc(paragraphs: list[str], indent: str = "    ") -> str:
    """Render wrapped paragraphs as one docstring."""
    blocks: list[str] = []
    for paragraph in paragraphs:
        text = ascii_text(paragraph).replace("\\", "\\\\").replace('"""', '\\"\\"\\"').strip()
        if text:
            blocks.append(wrap_paragraph(text, LINE_LIMIT - len(indent)))
    if not blocks:
        return ""
    body = "\n\n".join(blocks)
    if "\n" not in body and len(body) + len(indent) + 6 <= LINE_LIMIT and not body.endswith('"'):
        return f'{indent}"""{body}"""'
    indented = "\n".join(f"{indent}{line}" if line else "" for line in body.splitlines())
    return f'{indent}"""\n{indented}\n{indent}"""'


def render_model(item: EventModel) -> str:
    base = f"({item.base})" if item.base else ""
    lines = ["@model(kw_only=True)", f"class {item.name}{base}:", block_doc(item.paragraphs)]
    for f in item.fields:
        default = " = None" if f.optional else ""
        ignore = (
            "  # type: ignore[assignment]  # ty: ignore[incompatible-attribute-override]"
            if f.name in item.overrides
            else ""
        )
        lines.append(f"\n    {f.name}: {f.annotation}{default}{ignore}")
        if f.doc:
            lines.append(block_doc(f.doc.split("\n\n")))
    if not item.fields:
        lines.append("\n    pass" if not item.paragraphs else "")
    return "\n".join(lines)


def render_alias(name: str, expression: str, doc: str) -> str:
    text = docstring(ascii_text(doc.rstrip(".") + "."), indent="")
    return f"{name}: TypeAlias = {expression}\n{text}"


def module_of(page: str) -> str:
    return f"{RESOURCES_PACKAGE}.{module_name(page)}"


def render_events_module(plan: Plan, owner: dict[str, str]) -> str:
    items = [*plan.items, *plan.late]
    local = {item.name for item in items} | {name for name, _, _ in plan.aliases}
    used: set[str] = set()
    bodies: list[str] = []
    for item in items:
        if isinstance(item, Enum):
            bodies.append(render_enum(item))
        elif isinstance(item, EventModel):
            bodies.append(render_model(item))
            used.update(re.findall(r"[A-Za-z_]\w*", item.base))
            for f in item.fields:
                used.update(re.findall(r"[A-Za-z_]\w*", f.annotation))
        elif isinstance(item, Computed):
            bodies.append(render_computed(item))
    aliases = "\n\n".join(render_alias(*alias) for alias in plan.aliases)
    for _, expression, _ in plan.aliases:
        used.update(re.findall(r"[A-Za-z_]\w*", expression))
    exported = sorted(local)
    header = dedent(f'''\
        """Payload models for Discord's gateway events.

        {GENERATED_MARKER} from
        {DOCS_ROOT}/developers/{EVENTS_PAGE}. Do not edit by hand.
        """

        from __future__ import annotations

        ''')
    names = ", ".join(f'"{name}"' for name in exported)
    return (
        f"{header}{render_imports(items, used, owner, aliases=bool(plan.aliases))}\n"
        f"__all__ = [{names}]\n\n\n"
        + "\n\n\n".join(bodies)
        + (f"\n\n\n{aliases}\n" if aliases else "\n")
    )


def render_imports(
    items: list[Item], used: set[str], owner: dict[str, str], *, aliases: bool
) -> str:
    lines: list[str] = []
    if bases := sorted({item.base for item in items if isinstance(item, Enum)}):
        lines.append(f"from enum import {', '.join(bases)}\n")
    typing = [name for name, wanted in (("Any", "Any" in used), ("TypeAlias", aliases)) if wanted]
    if typing:
        lines.append(f"from typing import {', '.join(typing)}\n")
    if any(isinstance(item, EventModel) for item in items):
        lines.append("\nfrom dispyre.base import model\n")
    if scalars := sorted(used & {"ISO8601Timestamp", "Snowflake"}):
        lines.append(f"from {RESOURCES_PACKAGE}._types import {', '.join(scalars)}\n")
    local = {item.name for item in items}
    by_module: dict[str, list[str]] = {}
    for name in sorted(used - local):
        if name in owner:
            by_module.setdefault(module_of(owner[name]), []).append(name)
    lines.extend(
        f"from {module} import {', '.join(names)}\n" for module, names in sorted(by_module.items())
    )
    return "".join(lines)


def render_gateway_module(intents: list[Intent], notes: dict[int, str]) -> str:
    lines = [
        dedent(f'''\
            """Gateway intents.

            {GENERATED_MARKER} from
            {DOCS_ROOT}/developers/{GATEWAY_PAGE}. Do not edit by hand.
            """

            from __future__ import annotations

            from enum import IntFlag

            __all__ = ["GatewayIntents"]


            class GatewayIntents(IntFlag):
                """Bits for the `intents` field of Identify; each enables the events it lists."""
            ''')
    ]
    for intent in intents:
        lines.append(f"\n    {intent.name} = 1 << {intent.bit}")
        paragraphs = []
        if intent.events:
            paragraphs.append("Events: " + ", ".join(name for name, _ in intent.events) + ".")
        marks = {intent.marks, *(mark for _, mark in intent.events)} - {0}
        paragraphs.extend(f"Note: {notes[mark]}" for mark in sorted(marks) if mark in notes)
        if paragraphs:
            lines.append(block_doc(paragraphs, "    "))
    return "\n".join(lines) + "\n"


def render_registry(events: dict[str, EventDef]) -> str:
    send = [e for e in events.values() if e.direction == "send"]
    receive = [e for e in events.values() if e.direction == "receive"]
    exports = sorted({e.export for e in events.values() if e.export})
    header = dedent(f'''\
        """Every gateway event: its name, opcode, payload model and required intents.

        {GENERATED_MARKER}. Do not edit by hand.
        """

        from __future__ import annotations

        from dataclasses import dataclass
        from enum import StrEnum
        from typing import Any

        from {PACKAGE}.gateway import GatewayIntents
        from {PACKAGE}.gateway_events import {", ".join(exports)}

        __all__ = ["RECEIVE_EVENTS", "SEND_EVENTS", "EventInfo", "ReceiveEvent", "SendEvent"]


        @dataclass(frozen=True, slots=True)
        class EventInfo:
            """What the docs say about one gateway event."""

            title: str
            description: str
            category: str
            op: int | None
            """Opcode from the docs' example payload, if it shows one."""
            payload: Any
            """The class (or alias, or builtin type) the event's `d` decodes into."""
            intents: tuple[GatewayIntents, ...] = ()
            """Any one of these intents enables the event; empty means always sent."""
        ''')
    parts = [header]
    for enum_name, group in (("SendEvent", send), ("ReceiveEvent", receive)):
        members = "\n".join(f'    {e.wire} = "{e.wire}"' for e in group)
        parts.append(
            f"\nclass {enum_name}(StrEnum):\n"
            f'    """Names of the {enum_name[:-5].lower()} events."""\n\n{members}\n'
        )
    for mapping, enum_name, group in (
        ("SEND_EVENTS", "SendEvent", send),
        ("RECEIVE_EVENTS", "ReceiveEvent", receive),
    ):
        rows = []
        for e in group:
            payload = e.export or e.literal
            intents = "".join(f"GatewayIntents.{name}, " for name in e.intents)
            intents = f"({intents.rstrip()}) " if intents else "()"
            rows.append(
                f"    {enum_name}.{e.wire}: EventInfo(\n"
                f"        title={e.title!r},\n"
                f"        description={ascii_text(e.description)!r},\n"
                f"        category={e.category!r},\n"
                f"        op={e.op!r},\n"
                f"        payload={payload},\n"
                f"        intents={intents.strip()},\n"
                "    ),"
            )
        parts.append(
            f"\n{mapping}: dict[{enum_name}, EventInfo] = {{\n" + "\n".join(rows) + "\n}\n"
        )
    return "\n".join(parts)


def render_init(names: dict[str, list[str]]) -> str:
    imports = "".join(
        f"from {PACKAGE}.{module} import {', '.join(sorted(ns))}\n" for module, ns in names.items()
    )
    everything = sorted(name for ns in names.values() for name in ns)
    listing = "".join(f'    "{name}",\n' for name in everything)
    return (
        f'"""Models and registry for Discord\'s gateway events.\n\n'
        f'{GENERATED_MARKER}. Do not edit by hand.\n"""\n\n'
        f"{imports}\n__all__ = [\n{listing}]\n"
    )


def render_examples(events: dict[str, EventDef]) -> str:
    data: dict[str, dict[str, Any]] = {"send": {}, "receive": {}}
    for event in events.values():
        if event.example and "d" in event.example and event.kind != "literal":
            data[event.direction][event.wire] = event.example["d"]
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


