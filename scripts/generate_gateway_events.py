def generate(*, offline: bool) -> None:
    pages = load_pages(offline=offline, only=None, depth=2)
    events_md = load_page(EVENTS_PAGE, offline=offline)
    gateway_md = load_page(GATEWAY_PAGE, offline=offline)
    if events_md is None or gateway_md is None:
        msg = "gateway pages are not cached; run without --offline"
        raise SystemExit(msg)

    registry = Registry()
    per_page, resource_models, _ = collect(pages, registry, overrides=RESOURCE_OVERRIDES)
    for model in resource_models:
        build_model(model, registry)
    add_partials(per_page, registry)
    known_partials = set(registry.partials)
    owner = {item.name: page for page, items in per_page.items() for item in items}
    resources = {
        item.name: item for items in per_page.values() for item in items if isinstance(item, Model)
    }

    extra = example_models(pages, registry)
    events, tables = parse_events(events_md)
    plan = plan_events(events, tables, registry)
    build_models(plan, events, registry, resources)
    plan.models.extend(extra)
    plan.late.extend(extra)
    resources |= {model.name: model for model in extra}
    make_partials(plan, registry, resources, known_partials)
    intents = parse_intents(gateway_md)
    for intent in intents:
        for name, _ in intent.events:
            event = next((e for e in events.values() if e.wire == name), None)
            if event and intent.name not in event.intents:
                event.intents.append(intent.name)

    write_output(plan, events, intents, intent_notes(gateway_md), owner)
    report(plan, events, registry)


def write_output(
    plan: Plan,
    events: dict[str, EventDef],
    intents: list[Intent],
    notes: dict[int, str],
    owner: dict[str, str],
) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    EXAMPLES_FILE.parent.mkdir(parents=True, exist_ok=True)
    (OUTPUT_DIR / "gateway_events.py").write_text(render_events_module(plan, owner), "utf-8")
    (OUTPUT_DIR / "gateway.py").write_text(render_gateway_module(intents, notes), "utf-8")
    (OUTPUT_DIR / "registry.py").write_text(render_registry(events), "utf-8")
    names = {
        "gateway": ["GatewayIntents"],
        "gateway_events": sorted(
            {item.name for item in [*plan.items, *plan.late]} | {a[0] for a in plan.aliases}
        ),
        "registry": ["RECEIVE_EVENTS", "SEND_EVENTS", "EventInfo", "ReceiveEvent", "SendEvent"],
    }
    (OUTPUT_DIR / "__init__.py").write_text(render_init(names), "utf-8")
    EXAMPLES_FILE.write_text(render_examples(events), "utf-8")
    ruff = ["uv", "run", "ruff"]
    subprocess.run([*ruff, "check", "--fix", "--quiet", str(OUTPUT_DIR)], check=False)
    subprocess.run([*ruff, "format", "--quiet", str(OUTPUT_DIR)], check=True)


def report(plan: Plan, events: dict[str, EventDef], registry: Registry) -> None:
    kinds: dict[str, int] = {}
    for event in events.values():
        kinds[event.kind] = kinds.get(event.kind, 0) + 1
    print(
        f"\n{len(events)} events: " + ", ".join(f"{n} {kind}" for kind, n in sorted(kinds.items()))
    )
    print(f"{len(plan.models)} models, {len(plan.aliases)} aliases -> {OUTPUT_DIR}")
    for line in plan.skipped:
        print(f"skipped {line}")
    if registry.unresolved:
        print(f"\n{sum(registry.unresolved.values())} unresolved types:")
        for text, count in sorted(registry.unresolved.items(), key=lambda kv: -kv[1]):
            print(f"  {count:3}x  {text}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offline", action="store_true", help="only use cached pages")
    generate(offline=parser.parse_args().offline)


if __name__ == "__main__":
    main()
