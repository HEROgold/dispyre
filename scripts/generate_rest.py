#!/usr/bin/env python3
"""Generate the REST layer from Discord's OpenAPI spec, with the docs' markdown as fallback.

Sources, in order of trust:

1. `discord/discord-api-spec` (`openapi.json`). It defines every schema, parameter and
   operation, so the models, the route table and the client methods come from it.
2. The docs pages (see `docgen.py`). The spec has no descriptions, so each operation is
   matched to its docs section by `(method, path)` to add the summary, the first paragraph,
   the link, the descriptions of query and body fields, and the `X-Audit-Log-Reason` note.
   A docs endpoint the spec lacks becomes a route of its own, typed from its param tables.

Output goes to `src/dispyre/discord/rest/`:

- `schemas.py`: one class per spec schema. Objects become `@model` classes, `oneOf` lists of
  constants become enums, and other `oneOf`s become union aliases. Members of a union that
  share a `Literal` field (a component's `type`) decode by that field.
- `routes.py`: one `Route` per operation, plus `ROUTES` keyed by operation id.
- `client.py`: `RestApi`, an abstract client with one typed async method per route. A
  subclass implements `request` with its own HTTP library.
- `__init__.py`: exports the runtime types.

`route.py` (`Route`, `Requester`, `compact`) is written by hand.

Usage:
    uv run scripts/generate_rest.py            # fetch, cache and generate
    uv run scripts/generate_rest.py --offline  # regenerate from the cache only
"""

