def generate(*, offline: bool) -> None:
    spec = load_spec(offline=offline)
    endpoints = load_endpoints(offline=offline)
    schemas = Schemas(spec["components"]["schemas"])
    operations = build_operations(spec, schemas)
    leftovers = attach_docs(operations, endpoints, schemas)

    registry = Registry()
    registry.names.update(schemas.raw)
    taken = {op.id for op in operations}
    docs_only = [operation_from_docs(e, schemas, registry, taken) for e in leftovers]
    operations.extend(docs_only)
    operations.sort(key=lambda op: (op.path, op.method))

    schema_text = schemas.render()
    schema_names = set(schemas.enums) | set(schemas.models) | set(schemas.aliases)
    write_output(schema_text, operations, schema_names)
    report(operations, docs_only, schemas, registry)


def write_output(schema_text: str, operations: list[Operation], schema_names: set[str]) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    files = {
        "schemas.py": schema_text,
        "routes.py": render_routes(operations, schema_names),
        "client.py": render_client(operations, schema_names),
        "__init__.py": render_init(),
    }
    for name, text in files.items():
        (OUTPUT_DIR / name).write_text(text, "utf-8")
    ruff = ["uv", "run", "ruff"]
    subprocess.run([*ruff, "check", "--fix", "--quiet", str(OUTPUT_DIR)], check=False)
    subprocess.run([*ruff, "format", "--quiet", str(OUTPUT_DIR)], check=True)


def report(
    operations: list[Operation],
    docs_only: list[Operation],
    schemas: Schemas,
    registry: Registry,
) -> None:
    documented = sum(op.docs is not None for op in operations)
    print(
        f"\n{len(operations)} operations ({len(docs_only)} from the docs only), "
        f"{documented} with docs; {len(schemas.models)} models, {len(schemas.enums)} enums, "
        f"{len(schemas.aliases)} unions -> {OUTPUT_DIR}"
    )
    for op in docs_only:
        print(f"docs only: {op.method} {op.path} -> {op.id} (response typed Any)")
    for op in operations:
        if op.docs is None:
            print(f"no docs: {op.method} {op.path} ({op.id})")
    for line in schemas.problems:
        print(f"schema: {line}")
    if registry.unresolved:
        print(f"\n{sum(registry.unresolved.values())} unresolved types in docs-only params:")
        for text, count in sorted(registry.unresolved.items(), key=lambda kv: -kv[1]):
            print(f"  {count:3}x  {text}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offline", action="store_true", help="only use cached files")
    generate(offline=parser.parse_args().offline)


if __name__ == "__main__":
    main()
