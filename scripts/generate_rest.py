OUTPUT_DIR = REPO_ROOT / "src" / "dispyre" / "discord" / "rest"
PACKAGE = "dispyre.discord.rest"
TYPES_MODULE = "dispyre.discord.resources._types"
GENERATED_MARKER = "Generated by `scripts/generate_rest.py`"
PAGE_PREFIXES = ("resources/", "interactions/", "topics/", "events/", "social-layer/")
SCALARS = {"Snowflake", "ISO8601Timestamp"}
RESERVED_PARAMS = {"self", "body", "files", "reason"}
