MULTIPART = "multipart/form-data"
FORM = "application/x-www-form-urlencoded"


# --- data ------------------------------------------------------------------------------


@dataclass
class Param:
    """A path or query parameter."""

    wire: str
    name: str
    annotation: str
    required: bool
    doc: str = ""


@dataclass
class Operation:
    """One endpoint, from the spec or (when the spec lacks it) from the docs."""

    id: str
    method: str
    path: str
    source: str = "openapi"
    path_params: list[Param] = field(default_factory=list)
    query: list[Param] = field(default_factory=list)
    body: str = ""
    body_required: bool = False
    multipart: bool = False
    form: bool = False
    response: str = "None"
    bot: bool = False
    oauth2: bool = False
    scopes: list[str] = field(default_factory=list)
    anonymous: bool = False
    docs: Endpoint | None = None

    @property
    def const(self) -> str:
        return self.id.upper()

    @property
    def summary(self) -> str:
        return self.docs.name if self.docs else self.id.replace("_", " ").capitalize()


# --- schemas: OpenAPI -> Python annotations ------------------------------------------------


@dataclass
class Prop:
    wire: str
    name: str
    annotation: str
    optional: bool
    doc: str


@dataclass
class Schemas:
    """The spec's `components.schemas`, rendered as Python source."""

    raw: dict[str, dict[str, Any]]
    docs: dict[tuple[str, str], str] = field(default_factory=dict)
    """Field docs from the docs' param tables, keyed by `(schema, wire name)`."""
    origin: dict[str, Endpoint] = field(default_factory=dict)
    """Endpoint whose request body a schema is, for its docstring."""
    scalars: dict[str, str] = field(default_factory=dict)
    enums: dict[str, tuple[str, list[dict[str, Any]]]] = field(default_factory=dict)
    models: dict[str, list[Prop]] = field(default_factory=dict)
    aliases: dict[str, str] = field(default_factory=dict)
    extra: list[Model] = field(default_factory=list)
    """Models built from docs tables for endpoints the spec doesn't have."""
    problems: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        for name, schema in self.raw.items():
            kind = self.classify(schema)
            if kind == "enum":
                self.enums[name] = (schema["type"], schema["oneOf"])
            elif kind == "scalar":
                self.scalars[name] = ""
        for name in self.scalars:
            self.scalars[name] = self.annotation(self.raw[name])
        self.scalars |= {"SnowflakeType": "Snowflake"}
        for name, schema in self.raw.items():
            kind = self.classify(schema)
            if kind == "model":
                self.models[name] = self.props(name, schema)
            elif kind == "union":
                self.aliases[name] = self.annotation(schema)

    def ref(self, target: str) -> str:
        name = target.removeprefix(SCHEMA_PREFIX)
        return self.scalars.get(name, name)

    def annotation(self, schema: dict[str, Any]) -> str:
        """Python annotation for a schema; `| None` where the schema allows null."""
        if "$ref" in schema:
            return self.ref(schema["$ref"])
        if schema.get("enum"):
            return f"Literal[{', '.join(repr(value) for value in schema['enum'])}]"
        if options := schema.get("oneOf") or schema.get("anyOf"):
            return union(self.annotation(option) for option in options)
        if "allOf" in schema:
            return union(self.annotation(option) for option in schema["allOf"])
        kind = schema.get("type")
        if isinstance(kind, list):
            nullable = "null" in kind
            rest = [k for k in kind if k != "null"]
            parts = [self.annotation({**schema, "type": k}) for k in rest]
            return union([*parts, *(["None"] if nullable else [])])
        match kind:
            case "null":
                return "None"
            case "array":
                items = schema.get("items")
                return f"list[{self.annotation(items) if items else 'Any'}]"
            case "object":
                extra = schema.get("additionalProperties")
                value = self.annotation(extra) if isinstance(extra, dict) else "Any"
                return f"dict[str, {value}]"
            case "string":
                if schema.get("contentEncoding") == "binary":
                    return "bytes"
                return "ISO8601Timestamp" if schema.get("format") == "date-time" else "str"
            case "integer":
                return "int"
            case "number":
                return "float"
            case "boolean":
                return "bool"
        return "Any"

    def props(self, schema_name: str, schema: dict[str, Any]) -> list[Prop]:
        required = set(schema.get("required", []))
        props: list[Prop] = []
        seen: set[str] = set()
        for wire, spec in schema["properties"].items():
            name = identifier(wire)
            if name in seen:
                self.problems.append(f"{schema_name}.{wire} clashes with another field")
                continue
            seen.add(name)
            annotation = self.annotation(spec)
            optional = wire not in required
            if optional and "None" not in split_union(annotation):
                annotation = f"{annotation} | None"
            props.append(Prop(wire, name, annotation, optional, spec.get("description", "")))
        return props

    # -- rendering --

    def render(self) -> str:
        bodies = [self.render_enum(name, *spec) for name, spec in sorted(self.enums.items())]
        bodies += [self.render_model(name, props) for name, props in sorted(self.models.items())]
        bodies += [render_model(item) for item in self.extra]
        for item in self.extra:
            self.models[item.name] = [
                Prop(f.name, f.name, f.annotation, f.optional, f.doc) for f in item.fields
            ]
        aliases = "\n\n".join(self.render_aliases())
        header = dedent(f'''\
            """Models for every schema in Discord's OpenAPI spec.

            {GENERATED_MARKER} from
            https://github.com/discord/discord-api-spec. Do not edit by hand.
            """

            from __future__ import annotations

            ''')
        body = "\n\n\n".join(bodies)
        text = f"{body}\n\n\n{aliases}\n"
        return f"{header}{self.imports(text)}\n\n{text}"

    def imports(self, text: str) -> str:
        code = re.sub(r'"""[\s\S]*?"""', "", text)
        used = set(re.findall(r"[A-Za-z_]\w*", re.sub(r"'[^']*'", "", code)))
        lines = []
        bases = sorted(used & {"IntEnum", "StrEnum"})
        if bases:
            lines.append(f"from enum import {', '.join(bases)}\n")
        if "field" in used:
            lines.insert(0, "from dataclasses import field\n")
        typing = sorted(used & {"Any", "Literal", "TypeAlias"})
        if typing:
            lines.append(f"from typing import {', '.join(typing)}\n")
        lines.append("\nfrom dispyre.base import model\n")
        if scalars := sorted(used & SCALARS):
            lines.append(f"from {TYPES_MODULE} import {', '.join(scalars)}\n")
        return "".join(lines)

    def render_enum(self, name: str, kind: str, options: list[dict[str, Any]]) -> str:
        base = "StrEnum" if kind == "string" else "IntEnum"
        lines = [f"class {name}({base}):", docstring(f"{humanize(name)}.")]
        seen: set[str] = set()
        for option in options:
            member = constant(str(option.get("title") or option["const"]))
            if member in seen or not member.strip("_"):
                member = constant(f"{member}_{option['const']}")
            seen.add(member)
            lines.append(f"\n    {member} = {option['const']!r}")
            if option.get("description"):
                lines.append(docstring(option["description"], "    "))
        return "\n".join(lines)

    def render_model(self, name: str, props: list[Prop]) -> str:
        schema = self.raw[name]
        endpoint = self.origin.get(name)
        extra = f"Request body of {endpoint.name}: {endpoint.url}" if endpoint else ""
        summary = schema.get("description") or f"{humanize(name)}."
        lines = ["@model(kw_only=True)", f"class {name}:", docstring(summary, extra=extra)]
        if not props:
            lines.append("    pass" if not summary else "")
        for prop in props:
            lines.append(f"\n    {prop.name}: {prop.annotation}{prop_default(prop)}")
            if doc := prop.doc or self.docs.get((name, prop.wire), ""):
                lines.append(docstring(ascii_text(doc)))
        return "\n".join(lines)

    def render_aliases(self) -> list[str]:
        """Union aliases, dependencies first; a self-reference falls back to `Any`."""
        order: list[str] = []
        state: dict[str, int] = {}
        expressions = dict(self.aliases)

        def visit(name: str) -> None:
            if state.get(name):
                return
            state[name] = 1
            for dep in set(re.findall(r"[A-Za-z_]\w*", expressions[name])) & expressions.keys():
                if state.get(dep) == 1:  # on the stack: a cycle
                    expressions[name] = re.sub(rf"\b{dep}\b", "Any", expressions[name])
                    self.problems.append(f"{name} refers to itself; the reference became Any")
                else:
                    visit(dep)
            state[name] = 2
            order.append(name)

        for name in sorted(expressions):
            visit(name)
        return [render_alias(name, expressions[name], self.raw[name]) for name in order]

    @staticmethod
    def classify(schema: dict[str, Any]) -> str:
        options = schema.get("oneOf", [])
        if (
            schema.get("type") in {"string", "integer"}
            and options
            and all("const" in o for o in options)
        ):
            return "enum"
        if "oneOf" in schema or "anyOf" in schema or "allOf" in schema:
            return "union"
        if schema.get("type") == "object" and "properties" in schema:
            return "model"
        if schema.get("type") in {"string", "integer", "number", "boolean"} or "$ref" in schema:
            return "scalar"
        return "union"  # a bare object with additionalProperties becomes a dict alias


def union(parts: Iterable[str]) -> str:
    """Join annotations with `|`, dropping repeats and putting `None` last."""
    flat: list[str] = []
    for part in parts:
        flat.extend(split_union(part))
    unique = list(dict.fromkeys(flat))
    if "None" in unique:
        unique = [p for p in unique if p != "None"] + ["None"]
    return " | ".join(unique) or "Any"


def split_union(annotation: str) -> list[str]:
    """Split on the `|` at bracket depth 0."""
    parts, depth, start = [], 0, 0
    for i, char in enumerate(annotation):
        depth += char in "[("
        depth -= char in "])"
        if char == "|" and depth == 0:
            parts.append(annotation[start:i].strip())
            start = i + 1
    parts.append(annotation[start:].strip())
    return parts


def humanize(name: str) -> str:
    words = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", " ", name)
    return words[:1].upper() + words[1:].lower()


def prop_default(prop: Prop) -> str:
    key = prop.wire if prop.name not in {prop.wire, f"{prop.wire}_"} else ""
    if key:
        default = "default=None, " if prop.optional else ""
        return f' = field({default}metadata={{"key": {key!r}}})'
    return " = None" if prop.optional else ""


def render_alias(name: str, expression: str, schema: dict[str, Any]) -> str:
    summary = schema.get("description") or f"{humanize(name)}."
    return f"{name}: TypeAlias = {expression}\n{docstring(summary, indent='')}"


# --- operations ----------------------------------------------------------------------------


def normalize(path: str) -> str:
    return PATH_PARAM.sub("{}", re.sub(r"\{[^}]*\}", "{}", path))


def build_operations(spec: dict[str, Any], schemas: Schemas) -> list[Operation]:
    operations: list[Operation] = []
    for path, item in spec["paths"].items():
        shared = item.get("parameters", [])
        for method, raw in item.items():
            if method == "parameters":
                continue
            operation = Operation(raw["operationId"], method.upper(), path)
            params = {(p["in"], p["name"]): p for p in [*shared, *raw.get("parameters", [])]}
            for (where, wire), param in params.items():
                annotation = schemas.annotation(param.get("schema", {}))
                required = bool(param.get("required"))
                if not required and "None" not in split_union(annotation):
                    annotation = f"{annotation} | None"
                built = Param(
                    wire, identifier(wire), annotation, required, param.get("description", "")
                )
                (operation.path_params if where == "path" else operation.query).append(built)
            operation.path_params.sort(key=lambda p: path.find("{" + p.wire + "}"))
            read_body(operation, raw.get("requestBody"), schemas)
            read_response(operation, raw["responses"], schemas)
            read_security(operation, raw.get("security", []))
            operations.append(operation)
    return operations


def read_body(operation: Operation, body: dict[str, Any] | None, schemas: Schemas) -> None:
    if not body:
        return
    content = body.get("content", {})
    operation.body_required = bool(body.get("required"))
    operation.multipart = MULTIPART in content
    operation.form = FORM in content and "application/json" not in content
    chosen = content.get("application/json") or content.get(FORM) or content.get(MULTIPART)
    schema = (chosen or {}).get("schema", {})
    if "allOf" in schema and MULTIPART in content and "application/json" not in content:
        schema = schema["allOf"][0]  # the rest of the allOf is the `files[n]` parts
    operation.body = schemas.annotation(schema) if schema else "Any"


def read_response(operation: Operation, responses: dict[str, Any], schemas: Schemas) -> None:
    kinds: list[str] = []
    for status, response in responses.items():
        if not status.startswith("2"):
            continue
        content = response.get("content", {})
        if "application/json" in content:
            kinds.append(schemas.annotation(content["application/json"].get("schema", {})))
        elif "image/png" in content:
            kinds.append("bytes")
        elif "text/csv" in content:
            kinds.append("str")
        else:
            kinds.append("None")
    operation.response = union(kinds) if kinds else "None"


def read_security(operation: Operation, security: list[dict[str, list[str]]]) -> None:
    scopes: set[str] = set()
    for entry in security:
        operation.anonymous |= not entry
        operation.bot |= "BotToken" in entry
        if "OAuth2" in entry:
            operation.oauth2 = True
            scopes.update(entry["OAuth2"])
    operation.scopes = sorted(scopes)


# --- docs enrichment -----------------------------------------------------------------------


def load_endpoints(*, offline: bool) -> list[Endpoint]:
    if offline:
        paths = [p.stem.replace("__", "/") for p in sorted(CACHE_DIR.glob("*__*.md"))]
    else:
        found = DOC_URL.findall(fetch(INDEX_URL))
        paths = [p for p in dict.fromkeys(found) if p.startswith(PAGE_PREFIXES)]
    endpoints: list[Endpoint] = []
    for path in paths:
        if markdown := load_page(path, offline=offline):
            endpoints.extend(parse_endpoints(path, markdown))
    return endpoints


def param_tables(endpoint: Endpoint) -> tuple[list[Table], list[Table]]:
    """`(query tables, body tables)` among an endpoint's tables."""
    query, body = [], []
    for table in endpoint.tables:
        heading = plain(table.heading).lower()
        if not table.header or table.header[0].lower() != "field":
            continue
        if "query" in heading and "param" in heading:
            query.append(table)
        elif ("json" in heading or "form" in heading) and "param" in heading:
            body.append(table)
    return query, body


def table_docs(table: Table) -> dict[str, str]:
    """`{field name: description}` for a params table, with the default appended."""
    desc, default = column(table, "description"), column(table, "default")
    docs: dict[str, str] = {}
    for row in table.rows:
        if len(row) < 2 or desc is None or len(row) <= desc:  # noqa: PLR2004
            continue
        name = plain(row[0]).rstrip("*").rstrip("?").strip()
        text = plain(row[desc])
        if default is not None and len(row) > default and plain(row[default]) not in {"", "-"}:
            text = f"{text} Default: {plain(row[default])}."
        docs[name] = text
    return docs


def attach_docs(
    operations: list[Operation], endpoints: list[Endpoint], schemas: Schemas
) -> list[Endpoint]:
    """Match operations to docs sections; return the docs endpoints with no operation."""
    # Several pages can describe one route (a guide quoting a resource's endpoint). Prefer the
    # resource page, then the section with the most tables, so the pick doesn't depend on
    # the order the pages were read in.
    by_key: dict[tuple[str, str], Endpoint] = {}
    for endpoint in sorted(
        endpoints, key=lambda e: (not e.page.startswith("resources/"), -len(e.tables), e.page)
    ):
        by_key.setdefault(endpoint.key, endpoint)
    matched: set[tuple[str, str]] = set()
    for operation in operations:
        endpoint = by_key.get((operation.method, normalize(operation.path)))
        if endpoint is None:
            continue
        matched.add(endpoint.key)
        operation.docs = endpoint
        query_tables, body_tables = param_tables(endpoint)
        query_docs = {k: v for table in query_tables for k, v in table_docs(table).items()}
        for param in operation.query:
            param.doc = query_docs.get(param.wire, "") or param.doc
        target = operation.body.removesuffix(" | None")
        if target in schemas.models:
            schemas.origin.setdefault(target, endpoint)
            for table in body_tables:
                for key, text in table_docs(table).items():
                    schemas.docs.setdefault((target, key), text)
    return [e for e in by_key.values() if e.key not in matched]


def operation_from_docs(
    endpoint: Endpoint, schemas: Schemas, registry: Registry, taken: set[str]
) -> Operation:
    """Build a route from a docs section alone: params typed from its tables."""
    base = re.sub(r"\W+", "_", plain(re.sub(r"\(.*?\)", "", endpoint.name)).lower()).strip("_")
    op_id, n = base, 2
    while op_id in taken:
        op_id, n = f"{base}_{n}", n + 1
    taken.add(op_id)
    path = PATH_PARAM.sub(lambda m: "{" + "_".join(g for g in m.groups() if g) + "}", endpoint.path)
    operation = Operation(op_id, endpoint.method, path, source="docs", docs=endpoint)
    operation.path_params = [
        Param(wire, identifier(wire), "Snowflake" if wire.endswith("id") else "str", True)
        for wire in re.findall(r"\{([^}]+)\}", path)
    ]
    query_tables, body_tables = param_tables(endpoint)
    for table in query_tables:
        docs = table_docs(table)
        for row in table.rows:
            wire = plain(row[0]).rstrip("*").rstrip("?").strip()
            annotation, nullable = resolve_type(row[1], table.page, registry)
            required = not plain(row[0]).rstrip("*").endswith("?")
            if not required or nullable:
                annotation = f"{annotation} | None"
            operation.query.append(
                Param(wire, identifier(wire), annotation, required, docs.get(wire, ""))
            )
    if body_tables:
        name = registry.claim(pascal(op_id) + "Request", body_tables[0])
        model = Model(name, body_tables[0])
        build_model(model, registry)
        schemas.extra.append(model)
        schemas.raw.setdefault(name, {"description": f"Request body of {endpoint.name}."})
        operation.body, operation.body_required = name, True
    operation.response = "Any"
    operation.bot = operation.oauth2 = True
    return operation


# --- rendering: routes and client ----------------------------------------------------------


def literal(value: str) -> str:
    return repr(value)


def render_route(operation: Operation) -> str:
    docs = operation.docs
    fields = [
        f"operation_id={operation.id!r}",
        f"method={operation.method!r}",
        f"path={operation.path!r}",
    ]
    if operation.path_params:
        fields.append(f"path_params={tuple(p.wire for p in operation.path_params)!r}")
    if operation.query:
        fields.append(f"query={tuple(p.wire for p in operation.query)!r}")
    if required := tuple(p.wire for p in operation.query if p.required):
        fields.append(f"required_query={required!r}")
    if operation.body:
        fields.append(f"body={operation.body}")
        fields.append(f"body_required={operation.body_required}")
    for flag in ("multipart", "form"):
        if getattr(operation, flag):
            fields.append(f"{flag}=True")
    if operation.response != "None":
        fields.append(f"response={operation.response}")
    if docs:
        fields.append(f"summary={ascii_text(docs.name)!r}")
        fields.append(f"docs={docs.url!r}")
        if docs.audit_log_reason:
            fields.append("audit_log_reason=True")
        if docs.deprecated:
            fields.append("deprecated=True")
    for flag in ("bot", "oauth2", "anonymous"):
        if getattr(operation, flag):
            fields.append(f"{flag}=True")
    if operation.scopes:
        fields.append(f"oauth2_scopes={tuple(operation.scopes)!r}")
    if operation.source != "openapi":
        fields.append(f"source={operation.source!r}")
    body = ",\n    ".join(fields)
    return f"{operation.const} = Route(\n    {body},\n)"


def used_names(texts: list[str], known: set[str]) -> set[str]:
    """Return the identifiers in annotation strings that name a schema or a scalar alias."""
    found: set[str] = set()
    for text in texts:
        found.update(re.findall(r"[A-Za-z_]\w*", re.sub(r"'[^']*'", "", text)))
    return found & (known | SCALARS)


def import_block(names: set[str], schema_names: set[str]) -> str:
    lines = []
    if scalars := sorted(names & SCALARS):
        lines.append(f"from {TYPES_MODULE} import {', '.join(scalars)}\n")
    if models := sorted(names & schema_names):
        lines.append(f"from {PACKAGE}.schemas import {', '.join(models)}\n")
    return "".join(lines)


def annotation_texts(operations: list[Operation]) -> list[str]:
    texts = []
    for op in operations:
        texts += [op.body, op.response, *(p.annotation for p in [*op.path_params, *op.query])]
    return texts


def render_routes(operations: list[Operation], schema_names: set[str]) -> str:
    names = used_names(annotation_texts(operations), schema_names)
    texts = " ".join(annotation_texts(operations))
    typing = [n for n in ("Any", "Literal") if re.search(rf"\b{n}\b", texts)]
    header = dedent(f'''\
        """One `Route` per REST endpoint, and `ROUTES` to look them up by operation id.

        {GENERATED_MARKER} from the OpenAPI spec, with summaries and links
        from the docs. Do not edit by hand.
        """

        from __future__ import annotations

        ''')
    imports = (f"from typing import {', '.join(typing)}\n\n" if typing else "") + import_block(
        names, schema_names
    )
    imports += f"from {PACKAGE}.route import Route\n"
    routes = "\n\n".join(render_route(op) for op in operations)
    table = ",\n    ".join(f"{op.const}.operation_id: {op.const}" for op in operations)
    return f"{header}{imports}\n\n{routes}\n\nROUTES: dict[str, Route] = {{\n    {table},\n}}\n"


def method_signature(op: Operation) -> tuple[str, list[str]]:
    """Return the parameter list and the names given to the query parameters."""
    taken = {*RESERVED_PARAMS, *(p.name for p in op.path_params)}
    lines = ["self"]
    lines += [f"{p.name}: {p.annotation}" for p in op.path_params]
    keyword: list[str] = []
    if op.body:
        keyword.append(f"body: {op.body}" if op.body_required else f"body: {op.body} | None = None")
    if op.multipart:
        keyword.append("files: Mapping[str, bytes] | None = None")
    mapping: list[str] = []
    for param in sorted(op.query, key=lambda p: not p.required):
        name = param.name
        if name in taken:
            name = f"query_{name}"
        taken.add(name)
        param.name = name
        keyword.append(f"{name}: {param.annotation}" + ("" if param.required else " = None"))
        mapping.append(name)
    if op.docs and op.docs.audit_log_reason:
        keyword.append("reason: str | None = None")
    if keyword:
        lines += ["*", *keyword]
    return ", ".join(lines), mapping


def method_doc(op: Operation) -> str:
    docs = op.docs
    paragraphs = [f"{docs.name}." if docs else f"{op.summary}."]
    if docs and docs.description:
        paragraphs.append(docs.description)
    lines: list[str] = []
    for paragraph in paragraphs:
        lines += [*wrap(ascii_text(paragraph), LINE_LIMIT - 8), ""]
    lines.append(f"`{op.method} {op.path}`")
    if docs:
        lines.append(docs.url)
    if args := [f"{p.name}: {p.doc}" for p in op.query if p.doc]:
        lines += ["", "Args:"]
        for arg in args:
            wrapped = wrap(ascii_text(arg), LINE_LIMIT - 16)
            lines += [f"    {wrapped[0]}", *(f"        {line}" for line in wrapped[1:])]
    text = "\n".join(lines).replace("\\", "\\\\").replace('"""', "'''")
    body = "\n".join(f"        {line}" if line else "" for line in text.splitlines())
    return f'        """{body.lstrip()}\n        """'


def render_method(op: Operation) -> str:
    signature, query_names = method_signature(op)
    returns = op.response if op.response != "None" else "None"
    wire = {p.name: p.wire for p in op.query}
    call = [f"routes.{op.const}"]
    call.append("path={" + ", ".join(f'"{p.wire}": {p.name}' for p in op.path_params) + "}")
    query = ", ".join(f'"{wire[name]}": {name}' for name in query_names)
    call.append(f"query=compact({{{query}}})")
    if op.body:
        call.append("body=encode(body)")
    if op.multipart:
        call.append("files=files")
    if op.docs and op.docs.audit_log_reason:
        call.append("reason=reason")
    lines = [
        f"    async def {op.id}({signature}) -> {returns}:",
        method_doc(op),
    ]
    request = "await self.request(\n            " + ",\n            ".join(call) + ",\n        )"
    if returns == "None":
        lines.append(f"        {request}")
    elif returns in {"Any", "bytes", "str"}:
        lines.append(f"        return {request}")
    else:
        lines.append(f"        data = {request}")
        lines.append(f"        return decode({returns}, data)")
    return "\n".join(lines)


def render_client(operations: list[Operation], schema_names: set[str]) -> str:
    methods = "\n\n".join(render_method(op) for op in operations)
    texts = annotation_texts(operations)
    names = used_names(texts, schema_names)
    all_text = " ".join(texts)
    typing = [n for n in ("Any", "Literal") if re.search(rf"\b{n}\b", all_text)]
    header = dedent(f'''\
        """`RestApi`: every REST endpoint as a typed async method.

        {GENERATED_MARKER} from the OpenAPI spec, with summaries and links
        from the docs. Do not edit by hand.
        """

        from __future__ import annotations

        from typing import TYPE_CHECKING{", Any" if "Any" in typing else ""}{", Literal" if "Literal" in typing else ""}

        from {PACKAGE} import routes
        from {PACKAGE}.route import Requester, compact
        from dispyre.decode import decode, encode
        ''')
    imports = import_block(names, schema_names)
    return (
        f"{header}{imports}\n"
        "if TYPE_CHECKING:\n    from collections.abc import Mapping\n\n"
        '__all__ = ["RestApi"]\n\n\n'
        "class RestApi(Requester):\n"
        '    """Every endpoint as a method. Subclass it and implement `request`."""\n\n'
        f"{methods}\n"
    )


def render_init() -> str:
    return dedent(f'''\
        """Discord's REST API: routes, models and a typed client.

        {GENERATED_MARKER}. Do not edit by hand.
        """

        from {PACKAGE}.client import RestApi
        from {PACKAGE}.route import BASE_URL, Requester, Route, compact
        from {PACKAGE}.routes import ROUTES

        __all__ = ["BASE_URL", "ROUTES", "RestApi", "Requester", "Route", "compact"]
        ''')


